window.EXERCISE_CATALOG_BY_NAME = window.EXERCISE_CATALOG.reduce((index, exercise) => {
  [exercise.name, ...(exercise.aliases || [])].forEach((name) => {
    index[normalizeCatalogName(name)] = exercise.id;
  });

  return index;
}, {});

window.EXERCISE_CATALOG_BY_ID = window.EXERCISE_CATALOG.reduce((index, exercise) => {
  index[exercise.id] = exercise;
  return index;
}, {});

function normalizeCatalogName(name) {
  return String(name)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}
